import { test, expect } from '@playwright/test'
test('local empty dashboard, import validation and connections',async({page})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Which videos are gaining momentum?'})).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('Local database is not ready')
  await expect(page.getByText('No videos yet for these filters.')).toBeVisible()
  await page.getByLabel('Growth window').selectOption('7')
  await expect(page.getByText('Observed 7d change')).toBeVisible()
  await page.getByLabel('Import CSV').setInputFiles({name:'bad.csv',mimeType:'text/csv',buffer:Buffer.from('bad,columns\n1,2')})
  await expect(page.getByRole('status')).toContainText('CSV headers must be')
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('heading',{name:'Which videos are gaining momentum?'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true})
  await page.getByRole('link',{name:'Connections',exact:true}).click()
  await expect(page.getByText('Setup required',{exact:true})).toHaveCount(3)
  await expect(page.getByRole('img',{name:'facebook logo'})).toBeVisible()
  await expect(page.getByRole('img',{name:'instagram logo'})).toBeVisible()
  await expect(page.getByRole('img',{name:'tiktok logo'})).toBeVisible()
  await expect(page.getByRole('img',{name:'xiaohongshu logo'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Sync facebook now'})).toBeDisabled()
  await page.screenshot({path:'test-results/connections-mobile.png',fullPage:true})
})
test('legacy endpoints disabled and foreign writes rejected',async({request})=>{
  expect((await request.get('/api/cron/daily')).status()).toBe(410)
  expect((await request.post('/api/report/send')).status()).toBe(410)
  expect((await request.get('/api/metrics/tiktok')).status()).toBe(410)
  expect((await request.post('/api/videos/import',{headers:{origin:'https://example.com','content-type':'text/csv'},data:'bad'})).status()).toBe(403)
  expect((await request.post('/api/connections/tiktok/sync',{headers:{origin:'https://example.com'}})).status()).toBe(403)
  const unavailable=await request.post('/api/connections/xiaohongshu/sync',{headers:{origin:'http://127.0.0.1:3100'}})
  expect(unavailable.status()).toBe(400)
  const missing=await request.post('/api/connections/facebook/sync',{headers:{origin:'http://127.0.0.1:3100'}})
  expect(missing.status()).toBe(400)
  expect((await missing.json()).error).toContain('FB_PAGE_ID')
})
