/**
 * Brand customization — single source of truth.
 *
 * To rebrand the dashboard for your business:
 *   1. Edit the values below.
 *   2. Drop your logo files into /public/brand/ (light + dark SVG or PNG).
 *   3. Restart the dev server (or redeploy).
 *
 * You can also override `name`, `colors.primary`, and `colors.accent` at runtime
 * via the BRAND_NAME, BRAND_PRIMARY, BRAND_ACCENT env vars — handy for Vercel
 * deploys without forking.
 */
export interface BrandConfig {
  name: string
  tagline: string
  logo: { light: string; dark: string }
  favicon: string
  colors: {
    primary: string
    accent: string
    bg: string
    surface: string
    border: string
    fg: string
    muted: string
  }
  reportFooter: string
}

